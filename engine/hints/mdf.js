// 떠올리기 말 고르기 — bad(답 수 가운데 문제 글에 없는 수)가 하나도 들지 않은 첫 말 · 모두 걸리면 마지막 말(수 없는 말로 둠)
const NUM = /\d+(?:\.\d+)?/g;
const numsIn = (t) => (String(t).match(NUM) || []).map(Number);
function safe(ans, own, ...cands) {
  const o = new Set(own.map(Number)), bad = new Set(ans.map(Number).filter((v) => Number.isFinite(v) && !o.has(v)));
  for (const c of cands) if (!numsIn(c).some((v) => bad.has(v))) return c;
  return cands[cands.length - 1];
}
