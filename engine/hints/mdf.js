const qr = (a, b) => [Math.floor(a / b), a % b];
function divCue({ a, b }) {
  const [q, r] = qr(a, b);
  if (b <= 9 && q <= 9) return r ? `${b}단에서 ${eul(a)} 넘지 않는 가장 큰 곱을 찾아볼까요? 곱한 수가 몫, 남는 수가 나머지예요.` : `${b}에 몇을 곱하면 ${ga(a)} 될까요? 그 수가 몫이에요.`;
  if (b <= 9 && a < 100) {
    /* 몇십 ÷ 몇 — 그림(10짜리 동전 한 줄)과 같은 말 · '몇 개'만 물으면 1을 써서 '얼마'로 물음(처음 보는 눈 11-08) */
    if (ones(a) === 0 && tens(a) % b === 0) return safe([q, r], [a, b], `${eun(a)} 10이 ${tens(a)}개예요. ${b}묶음으로 똑같이 나누면 한 묶음은 얼마일까요?`, `${eun(a)} 십이 ${tens(a)}개예요. ${b}묶음으로 똑같이 나누면 한 묶음은 얼마일까요?`);
    const x = Math.floor(a / (10 * b)) * 10 * b, y = a - x;
    if (y < b) return `${a} 중에서 ${eul(x)} 먼저 나눠 볼까요? 남는 수가 나머지예요.`;   /* 가른 뒤쪽 수가 곧 나머지라 말하지 않음 */
    return safe([q, r], [a, b], `${eul(a)} ${cut([x, y])} 갈라서 나눠 볼까요?`, `${x} ÷ ${b}부터 해 볼까요? 남은 수도 ${RO(b)} 나눠요.`, `몇십부터 ${RO(b)} 나눠 볼까요?`);
  }
  if (b <= 9) {
    const h = Math.floor(a / 100), down = (w) => `남은 수 옆에 ${w} 자리 숫자를 내려 써서 다시 나눠요.`;
    if (h < b) return safe([q, r], [a, b], `백의 자리 ${eun(h)} ${b}보다 작으니 앞의 두 자리 ${Math.floor(a / 10)}부터 나눠 볼까요? ${down('일의')}`, `백의 자리 숫자가 ${b}보다 작으니 앞의 두 자리부터 나눠 볼까요? ${down('일의')}`);
    return `백의 자리부터 ${RO(b)} 나눠 볼까요? ${down('다음')}`;
  }
  // 두 자리 수로 나누기 — 몫이 한 자리면 그림(수직선에서 나누는 수씩 뛰기)과 같은 말
  if (q <= 9) {
    const jump = r ? `${b}씩 몇 번 뛰면 ${eul(a)} 넘지 않고 가장 가까이 갈까요?` : `${b}씩 몇 번 뛰면 ${ga(a)} 될까요?`;
    if (b % 10 === 0) return jump;
    const t = Math.round(b / 10) * 10 || 10;
    return safe([q, r], [a, b], `${jump} ${eul(b)} ${RO(t)} 어림하면 짐작하기 쉬워요.`, `${jump} ${eul(b)} 가까운 몇십으로 어림하면 짐작하기 쉬워요.`);
  }
  const f2 = Math.floor(a / 10);
  return safe([q, r], [a, b], `앞의 두 자리 ${f2} 안에 ${ga(b)} 몇 번 들어갈까요? 그 수가 몫의 십의 자리예요.`, `앞의 두 자리 안에 ${ga(b)} 몇 번 들어갈까요? 그 수가 몫의 십의 자리예요.`);
}
