const st = (c, p, why, name) => ({ c, p, why, name });
function factSteps(a, b) {
  if (b <= 1 || a <= 1) return [];
  const same = (x) => st('ADD', { a: x, b: x }, `${x}${P(x, '과', '와')} ${eul(x)} 더해요.`, '같은 수 두 번 더하기');
  if (b === 2) return [same(a)];
  const known = (x) => st('MUL', { a: x, b }, `${x} × ${eul(b)} 구해요.`, '아는 단의 곱 구하기');
  const twice = (x) => [st('MUL', { a: x, b }, `${x} × ${eul(b)} 구해요.`, '절반인 수로 먼저 곱하기'), st('ADD', { a: x * b, b: x * b }, '그 곱을 두 번 더해요.', '그 곱을 두 번 더하기')];
  if (a === 2) return [same(b)];
  if (a === 3) return [known(2), st('ADD', { a: 2 * b, b }, `그 곱에 ${eul(b)} 더해요.`, '남은 묶음 더하기')];
  if (a === 4) return twice(2);
  if (a === 6) return twice(3);
  if (a === 8) return twice(4);
  if (a === 5) {
    const rest = (x) => st('ADD', { a: x, b: 5 }, '남은 5를 더해요.', '남은 묶음 더하기');
    if (b === 3) return [same(5), rest(10)];
    const e = b % 2 ? b - 1 : b, out = [st('N5', { v: 'tens', k: e / 2 }, `5씩 ${e}묶음을 두 묶음씩 짝 지으면 10이 ${e / 2}개예요. 얼마인지 구해요.`, '짝 지어 10씩 세기')];
    if (b % 2) out.push(rest(5 * e));
    return out;
  }
  if (a === 7) return [known(5), st('MUL', { a: 2, b }, `2 × ${eul(b)} 구해요.`, '다른 단의 곱 구하기'), st('ADD', { a: 5 * b, b: 2 * b }, '두 곱을 더해요.', '두 곱 더하기')];
  if (a === 9) return [st('N5', { v: 'tens', k: b }, `10씩 ${b}묶음을 세어요.`, '10씩 묶음 세기'), st('SUB', { a: 10 * b, b }, `${eul(b)} 빼요.`, '묶음 수만큼 빼기')];
  return [];
}
