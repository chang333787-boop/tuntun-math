// 문제 수 나누기 — share 비율대로(남는 것은 앞 갈래부터) · 문제 수가 갈래 수 이상이면 갈래마다 적어도 1
//  shares를 주면 그 비율로(0인 갈래는 뺌 — 아이 칸 위주 focusShares)
export function splitN(s, n, shares = null) {
  const sh = shares || s.parts.map((p) => p.share || 1), tot = sh.reduce((a, b) => a + b, 0) || 1;
  const raw = sh.map((w) => (n * w) / tot), out = raw.map(Math.floor);
  let left = n - out.reduce((a, b) => a + b, 0);
  const ord = raw.map((x, i) => [x - Math.floor(x), i]).filter(([, i]) => sh[i] > 0).sort((a, b) => b[0] - a[0] || a[1] - b[1]);
  for (let k = 0; left > 0 && ord.length; k = (k + 1) % ord.length) { out[ord[k][1]]++; left--; }
  const live = sh.map((w, i) => (w > 0 ? i : -1)).filter((i) => i >= 0);
  if (n >= live.length) for (const i of live) if (!out[i]) { const j = out.indexOf(Math.max(...out)); out[j]--; out[i]++; }
  return out;
}
// 아이 칸 위주 — 그 아이 칸(focus)은 2 · 그 앞(쉬운 갈래)은 1 · 그 뒤(더 어려운 갈래)는 0(뺌) · 이 기능에 그 아이 칸이 없으면 null(기본 나누기)
export function focusShares(s, focus) {
  const f = new Set(focus || []), idx = s.parts.map((p, i) => (f.has(p.c) ? i : -1)).filter((i) => i >= 0);
  if (!idx.length || s.mix || s.parts.length < 2) return null;
  const last = Math.max(...idx);
  return s.parts.map((p, i) => (f.has(p.c) ? 2 : i < last ? 1 : 0));
}
// 갈래마다 시작 번호(1부터) — 0문제인 갈래는 null
export function startsOf(s, n, shares = null) {
  const ns = splitN(s, n, shares); let at = 1;
  return ns.map((k) => { const v = k ? at : null; at += k; return v; });
}
// 아이에게 보일 지시 한 줄 — {k}를 그 갈래의 시작 번호로 · 그 갈래가 비었거나 맨 처음이면 그 문장을 뺌
export function noteOf(s, n, shares = null) {
  const st = startsOf(s, n, shares);
  return String(s.note || '').split(/(?<=[.?!])\s+/).map((t) => {
    let ok = true;
    const out = t.replace(/\{(\d)\}/g, (_, k) => { const v = st[Number(k) - 1]; if (!v || v === 1) ok = false; return String(v); });
    return ok ? out : '';
  }).filter(Boolean).join(' ');
}
// 맞춤 연습지 설정의 갈래 하나(paper/js/pick.js buildSheet가 읽음) — want = { 차시: 오개념 카드 id }(그 생각으로 풀면 틀리는 함정 꼴을 절반) · shares = 갈래 비율(focusShares)
export function secOf(s, n, { want = {}, shares = null } = {}) {
  const ns = splitN(s, n, shares);
  const it = s.parts.map((p, i) => ({ c: p.c, n: ns[i], ...(p.re ? { re: p.re } : {}), ...(want[p.c] ? { want: want[p.c] } : {}) })).filter((x) => x.n > 0);
  return { t: s.name, note: noteOf(s, n, shares), ...(s.dup ? { dup: s.dup } : {}), ...(s.mix ? { mix: 1 } : {}), it };
}
// 선생님 화면 — 갈래마다 몇 문제(예: '받아내림 없이 4 · 몇십 − 몇십몇 3 · 받아내림 3') · 갈래가 하나면 빈 글
export function partsText(s, n, shares = null) {
  if (s.parts.length < 2) return '';
  const ns = splitN(s, n, shares);
  return s.parts.map((p, i) => (ns[i] ? `${p.label} ${ns[i]}` : '')).filter(Boolean).join(' · ');
}
