export const PLAN_FALLBACK = '한 단계 풀기';   /* 이름을 못 붙인 단계(시험이 잡음 — 새 단계 글을 쓰면 PLAN_RULES에 줄을 더함) */
function stepName(c, s, i, steps, p) {
  if (s.name) return s.name;
  const sp = planSpecial(c, s, i, steps, p);
  if (sp) return sp;
  for (const [re, nm] of PLAN_RULES) { const m = String(s.why || '').match(re); if (m) return typeof nm === 'function' ? nm(m) : nm; }
  return PLAN_FALLBACK;
}
export function planNames(c, p, steps) {
  let xs = steps;
  if (!xs) { try { xs = stepsOf(c, p); } catch (e) { xs = []; } }
  return xs.map((s, i) => stepName(c, s, i, xs, p));
}
for (const c of Object.keys(HINTS_MDF)) HINTS_MDF[c] = { ...HINTS_MDF[c], plan: (p, steps) => planNames(c, p, steps) };

export default HINTS_MDF;
