import { makeItem } from '../engine/concepts/index.js';
import { toText } from '../engine/tokens.js';
const cases = [
  ['3 : 4 = □ : 12', 'R9'], ['□ : 4 = 9 : 12', 'R9'], ['3:4=9:?', 'R9'], ['35를 3 : 4로 비례배분', 'R10'], ['3/4 ÷ 2/5', 'F19'], ['6/7 ÷ 2/7', 'F18'],
  ['6 ÷ 3/4', 'F21'], ['1 ÷ 3/4', 'F21'], ['2/3 × 4/5', 'F15'], ['1/3 × 1/5', 'F15a'], ['12 × 2/3', 'F14'], ['2/5 × 3', 'F13'], ['3/4 ÷ 2', 'F17'],
  ['1/2 + 1/3', 'F12'], ['5/6 - 1/4', 'F12'], ['2/5 + 1/5', 'F6'], ['3/4, 5/6 통분', 'F9'], ['12/18 약분', 'F8'], ['12와 18의 최대공약수', 'G3'],
  ['4와 6의 최소공배수', 'G4'], ['58 × 37', 'M10'], ['47 × 6', 'M8'], ['6 × 47', 'M8'], ['7 × 8', 'M6'], ['40 × 30', 'M9'], ['58 × 30', 'M9'], ['30 × 4', 'M7'],
  ['72 ÷ 3', 'D6'], ['17 ÷ 5', 'D5'], ['42 ÷ 7', 'D4'], ['736 ÷ 23', 'D7'], ['3 ÷ 4', 'F16'], ['7 ÷ 3 몫을 분수로', 'F16'], ['61 - 27', 'A6'], ['38 + 47', 'A5'],
  ['8 + 5', 'A3'], ['3 + 4', 'A1'], ['13 - 5', 'A4'], ['367 + 485', 'A8'], ['12의 2/3', 'F4'], ['17/20 백분율', 'R5'], ['0.35를 백분율로', 'R5'],
  ['3 : 5의 비율', 'R4'], ['18 : 24를 간단한 자연수의 비로', 'R7'], ['0.6 : 0.9 간단히', 'R7'], ['1/2 : 1/3 간단한 자연수의 비', 'R7'], ['2/3 = □/12', 'F7'],
  ['8/12 = □/3', 'F7'], ['2 1/3 = □/3', 'F5'], ['2와 1/3 ÷ 3/8', 'F19'], ['1/3 ○ 1/5', 'F2'], ['3/5 ○ 4/7', 'F10'], ['3/5 ○ 2/5', 'F3'], ['□ + 5 = 12', 'A7'],
  ['3 + 5 = □ + 6', 'R0'], ['12는 4의 몇 배', 'R2'], ['0.35 × 100', 'DEC4'], ['3/5를 소수로', 'F11'], ['12의 약수', 'G1'], ['2 1/4 ÷ 3/8', 'F19'], ['3/4 나누기 2/5', 'F19'], ['58 곱하기 37', 'M10'], ['38 더하기 47', 'A5'], ['61 빼기 27', 'A6'], ['58 x 37', 'M10'], ['58*37', 'M10'],
];
let f = 0;
for (const [s, want] of cases) {
  const r = parseProblem(s);
  if (r.error || r.c !== want) { f++; console.log('✗', s, '→', r.error || r.c, '(원함', want + ')'); continue; }
  const it = makeItem(r.c, r.p);
  if (!it.check(it.sol.map(Number), it.sol.map(String)).ok) { f++; console.log('✗ 정답 확인 실패', s); }
  if (process.env.V) console.log('✓', s.padEnd(22), r.c.padEnd(5), toText(it.prompt), '→', it.ans);
}
EXAMPLES.forEach((s) => { const r = parseProblem(s); if (r.error) { f++; console.log('✗ 예시', s, r.error); } });
for (const s of ['', '안녕', '3 ÷ 0', '5 − 9']) { const r = parseProblem(s); if (!r.error) { f++; console.log('✗ 오류여야 함', s, r.c); } }
console.log(`입력 ${cases.length}개 · 실패 ${f}`);
process.exit(f ? 1 : 0);
